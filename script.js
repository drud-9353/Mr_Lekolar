/* =========================================================
   PAGE SYSTEM
========================================================= */

function hideAllPages() {
  document.querySelectorAll(".page").forEach(function(page) {
    page.style.display = "none";
  });
}


/* =========================================================
   START
========================================================= */

function startGame() {
  hideAllPages();

  if (!playerName) {
    document.getElementById("accountPage").style.display = "flex";
  } else {
    showCases();
  }
}


function showCases() {
  hideAllPages();

  const page = document.getElementById("cases");

  if (!page) return;

  page.style.display = "flex";

  const welcome = document.getElementById("welcomeText");

  if (welcome) {
    welcome.innerText =
    "بەخێربێیت لێکۆڵەر" + playerName + " 🕵️‍♂️";
  }

  updatePlayerStats();
  renderCases();
}


/* =========================================================
   ACCOUNT
========================================================= */

function createAccount() {

  const name =
    document.getElementById("accountName").value.trim();

  const password =
    document.getElementById("accountPassword").value;

  const message =
    document.getElementById("accountMessage");

  if (name.length < 2) {
    message.innerText =
      "❌ ناوەکە دەبێت لانیکەم ٢ پیت بێت.";
    return;
  }

  if (password.length < 4) {
    message.innerText =
      "❌ وشەی نهێنی دەبێت لانیکەم ٤ پیت بێت.";
    return;
  }

  playerName = name;

  localStorage.setItem("playerName", playerName);
  localStorage.setItem("playerPassword", password);

  const key =
    "mr_player_" + name.toLowerCase();

  const account = {
    name: playerName,
    password: password,
    xp: playerXP,
    points: playerPoints,
    solved: solvedCases,
    cases: caseSolved,
    avatar: selectedAvatar
  };

  localStorage.setItem(
    key,
    JSON.stringify(account)
  );

  showCases();
}


/* =========================================================
   RANK
========================================================= */

function getRank() {

  if (playerXP < 100)
    return "نوێکار";

  if (playerXP < 300)
    return "ملازم";

  if (playerXP < 600)
    return "کاپتن";

  if (playerXP < 1000)
    return "عقید";

  return "سەرلێکۆڵەر 🕵️‍♂️";
}


/* =========================================================
   STATS
========================================================= */

function updatePlayerStats() {

  const xp = document.getElementById("xp");
  const points = document.getElementById("points");
  const rank = document.getElementById("rank");
  const solved = document.getElementById("solvedCases");

  if (xp) xp.innerText = playerXP;
  if (points) points.innerText = playerPoints;
  if (rank) rank.innerText = getRank();
  if (solved) solved.innerText = solvedCases;
}


/* =========================================================
   CASE LIST
========================================================= */

function renderCases() {

  const list =
    document.getElementById("caseList");

  if (!list) return;

  list.innerHTML = "";

  cases.forEach(function(gameCase) {

    const unlocked =
      gameCase.id === 1 ||
      solvedCases >= gameCase.id - 1;

    const solved =
      caseSolved[gameCase.id];

    const card =
      document.createElement("div");

    card.className =
      "case-card" +
      (unlocked ? "" : " locked");

    let buttonText;

    if (solved) {
      buttonText = "✅ چارەسەر کراوە";
    } else if (unlocked) {
      buttonText = "🔎 دەستکردن بە لێکۆڵینەوە";
    } else {
      buttonText = "🔒 قفڵە";
    }

    card.innerHTML = `
      <h2>🔎 دۆسیەی ${gameCase.id}</h2>
      <p>${gameCase.title}</p>
      <small>⚡ ${gameCase.difficulty}</small>
      <button>${buttonText}</button>
    `;

    const button =
      card.querySelector("button");

    if (unlocked) {

      button.onclick = function() {
        openCase(gameCase.id);
      };

    } else {

      button.onclick = function() {

        alert(
          "🔒 سەرەتا دۆسیەی " +
          (gameCase.id - 1) +
          " چارەسەر بکە!"
        );

      };
    }

    list.appendChild(card);
  });
}


/* =========================================================
   OPEN CASE
========================================================= */

function openCase(caseId) {

  currentCase =
    cases.find(function(item) {
      return item.id === caseId;
    });

  if (!currentCase) return;

  currentSuspect = null;

  hideAllPages();

  document.getElementById("casePage")
    .style.display = "flex";

  document.getElementById("caseNumber")
    .innerText =
    "دۆسیەی ژمارە " +
    currentCase.id +
    " — " +
    currentCase.difficulty;

  document.getElementById("caseTitle")
    .innerText =
    currentCase.title;

  document.getElementById("caseStory")
    .innerText =
    currentCase.story;

  renderSuspects();
  renderClues();
  renderAnswers();
  setupSuspects();

  document.getElementById("chatBox")
    .innerHTML =
    `<p class="chat-empty">
      گومان‌لێکراو هەڵبژێرە بۆ دەستپێکردنی گفتوگۆ.
    </p>`;

  document.getElementById("chatInput").value = "";
}


