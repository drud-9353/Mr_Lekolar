/* =========================================================
   SOUND
========================================================= */

function playTone(
  frequency,
  duration,
  type = "sine"
) {

  try {

    const AudioContext =
      window.AudioContext ||
      window.webkitAudioContext;

    const audio =
      new AudioContext();

    const oscillator =
      audio.createOscillator();

    const gain =
      audio.createGain();

    oscillator.type = type;

    oscillator.frequency.value =
      frequency;

    oscillator.connect(gain);
    gain.connect(audio.destination);

    gain.gain.setValueAtTime(
      .12,
      audio.currentTime
    );

    gain.gain.exponentialRampToValueAtTime(
      .001,
      audio.currentTime + duration
    );

    oscillator.start();

    oscillator.stop(
      audio.currentTime + duration
    );

  } catch(e) {}
}


function playWinSound() {

  playTone(523,.15);

  setTimeout(
    () => playTone(659,.15),
    160
  );

  setTimeout(
    () => playTone(784,.25),
    320
  );
}


function playLoseSound() {

  playTone(
    220,
    .25,
    "sawtooth"
  );

  setTimeout(
    () => playTone(
      150,
      .35,
      "sawtooth"
    ),
    220
  );
}


