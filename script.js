function switchAccount() {

  const answer =
    prompt(
      "ناوی ئەکاونتی نوێ بنووسە:"
    );

  if (!answer) return;

  const name =
    answer.trim();

  if (!name) return;

  const password =
    prompt("وشەی نهێنی:");

  if (!password) return;

  const key =
    "mr_player_" +
    name.toLowerCase();

  const saved =
    localStorage.getItem(key);

  if (saved) {

    const account =
      JSON.parse(saved);

    if (account.password !== password) {

      alert(
        "❌ وشەی نهێنی هەڵەیە."
      );

      return;
    }

    loadAccount(account);

  } else {

    const account = {

      name: name,
      password: password,
      xp: 0,
      points: 0,
      solved: 0,
      cases: {},
      avatar: "🕵️‍♂️"

    };

    localStorage.setItem(
      key,
      JSON.stringify(account)
    );

    loadAccount(account);
  }
}


